// Derives prisma/postgres/schema.prisma from the SQLite schema so both stay identical apart from the provider.
// Run after changing prisma/schema.prisma, then regenerate the PostgreSQL migration (see docs/DATABASE_SCHEMA.md).
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const source = readFileSync("prisma/schema.prisma", "utf8");
if (!source.includes('provider = "sqlite"')) {
  console.error("Expected the main schema to use the sqlite provider.");
  process.exit(1);
}
const banner = "// GENERATED by scripts/make-pg-schema.mjs from prisma/schema.prisma. Do not edit by hand.\n";
mkdirSync("prisma/postgres", { recursive: true });
writeFileSync("prisma/postgres/schema.prisma", banner + source.replace('provider = "sqlite"', 'provider = "postgresql"'));
console.log("Wrote prisma/postgres/schema.prisma");
